-- RideSafe live location database
-- Enable Anonymous Sign-Ins in Supabase Auth before using the app.

create extension if not exists pgcrypto;

-- =========================================================
-- SAFETY SESSIONS
-- =========================================================

create table if not exists public.safety_sessions (
  id uuid primary key default gen_random_uuid(),

  user_id uuid not null
    references auth.users(id)
    on delete cascade,

  type text not null
    check (
      type in (
        'location_share',
        'safe_ride',
        'unsafe_alert',
        'emergency'
      )
    ),

  share_token uuid not null unique,

  destination text,

  status text not null default 'active',

  started_at timestamptz not null default now(),

  ended_at timestamptz
);

-- =========================================================
-- LOCATION POINTS
-- =========================================================

create table if not exists public.location_points (
  id bigint generated by default as identity primary key,

  session_id uuid not null
    references public.safety_sessions(id)
    on delete cascade,

  latitude double precision not null,

  longitude double precision not null,

  accuracy double precision,

  battery_level double precision,

  recorded_at timestamptz not null default now()
);

-- =========================================================
-- SAFETY EVENTS
-- =========================================================

create table if not exists public.safety_events (
  id bigint generated by default as identity primary key,

  session_id uuid not null
    references public.safety_sessions(id)
    on delete cascade,

  event_type text not null,

  payload jsonb not null default '{}'::jsonb,

  created_at timestamptz not null default now()
);

-- =========================================================
-- INDEXES
-- Important because the viewer repeatedly asks for the
-- newest location/event for a session.
-- =========================================================

create index if not exists
  location_points_session_recorded_idx
on public.location_points (
  session_id,
  recorded_at desc
);

create index if not exists
  safety_events_session_created_idx
on public.safety_events (
  session_id,
  created_at desc
);

create index if not exists
  safety_sessions_share_token_idx
on public.safety_sessions (
  share_token
);

-- =========================================================
-- ROW LEVEL SECURITY
-- =========================================================

alter table public.safety_sessions
enable row level security;

alter table public.location_points
enable row level security;

alter table public.safety_events
enable row level security;

